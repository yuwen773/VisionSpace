package com.yuwen.visionspace.acceptance;

import com.yuwen.visionspace.mapper.McpServerMapper;
import com.yuwen.visionspace.mapper.PictureMapper;
import com.yuwen.visionspace.model.entity.McpServer;
import com.yuwen.visionspace.model.entity.Picture;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.Date;

import static org.junit.jupiter.api.Assertions.assertArrayEquals;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * 真实 PostgreSQL 上的 JDBC 类型映射，跑在真库而不是 mock 上。
 *
 * <p>MySQL 与 PostgreSQL 在下面几处返回<strong>不同的 Java 类型</strong>，靠单元测试和
 * 类型推断都发现不了，只有连真库才会暴露：
 * <ul>
 *   <li>{@code bytea} ↔ {@code byte[]}（MySQL 的 {@code blob} 映射路径不同）；</li>
 *   <li>{@code GENERATED BY DEFAULT AS IDENTITY} 插入后回填主键（MyBatis Plus {@code IdType.AUTO}）；</li>
 *   <li>{@code numeric} 的标度（MySQL {@code decimal} 的默认标度规则不同）；</li>
 *   <li>聚合类型：PG 的 {@code count(*)}→bigint、{@code sum(int4)}→bigint、
 *       {@code sum(int8)}→numeric、{@code avg()}→numeric，与 MySQL 的返回类型不完全一致；</li>
 *   <li>{@code smallint} ↔ {@code Integer}（tinyint 迁移后的实体字段仍是 Integer）；</li>
 *   <li>{@code timestamp(0)} ↔ {@code LocalDateTime}，秒级精度、无时区偏移。</li>
 * </ul>
 */
@IsolatedSpringBootTest
class PostgresJdbcMappingTest {

    private static final long PICTURE_ID = 9_151_001L;
    private static final long PICTURE_AGG_A = 9_151_011L;
    private static final long PICTURE_AGG_B = 9_151_012L;
    private static final long RUN_STATE_ID = 9_151_002L;
    private static final long STATS_ID = 9_151_003L;
    private static final long OWNER_ID = 9_151_000L;
    private static final String THREAD_ID = "acceptance-mapping-thread";
    private static final String MCP_CODE = "acceptance-mapping-mcp";

    @Autowired
    private JdbcTemplate jdbc;

    @Autowired
    private McpServerMapper mcpServerMapper;

    @Autowired
    private PictureMapper pictureMapper;

    @AfterEach
    void cleanUp() {
        jdbc.update("DELETE FROM picture_stats WHERE id = ?", STATS_ID);
        jdbc.update("DELETE FROM agent_run_state WHERE id = ?", RUN_STATE_ID);
        jdbc.update("DELETE FROM picture WHERE user_id = ?", OWNER_ID);
        jdbc.update("DELETE FROM mcp_server WHERE mcp_server_code IN (?, ?)", MCP_CODE, MCP_CODE + "-2");
    }

    @Test
    void byteaRoundTripsAsByteArray() {
        // 含 0x00 与 0xFF：字符串中转或字符集转换会破坏它们，只有真正的二进制列能原样往返。
        byte[] payload = {0x00, 0x01, 0x7F, (byte) 0x80, (byte) 0xFF, 0x00};
        jdbc.update("""
                INSERT INTO agent_run_state (id, thread_id, user_id, state_format, state_payload)
                VALUES (?, ?, 9_151_000, 'acceptance', ?)
                """, RUN_STATE_ID, THREAD_ID, payload);

        byte[] restored = jdbc.queryForObject(
                "SELECT state_payload FROM agent_run_state WHERE id = ?", byte[].class, RUN_STATE_ID);
        assertArrayEquals(payload, restored, "bytea 必须逐字节往返，不能被当成文本编码再解码");
        assertEquals(payload.length, jdbc.queryForObject(
                "SELECT length(state_payload) FROM agent_run_state WHERE id = ?", Integer.class, RUN_STATE_ID));
    }

    @Test
    void identityColumnFillsTheEntityAfterInsert() {
        McpServer server = new McpServer();
        server.setMcpServerCode(MCP_CODE);
        server.setUserId(9_151_000L);
        server.setName("acceptance-mapping");
        server.setDeployConfig("{}");

        assertEquals(1, mcpServerMapper.insert(server));
        assertNotNull(server.getId(), "IdType.AUTO 依赖 IDENTITY 的 generated keys 回填，PG 上必须同样生效");
        assertEquals(server.getId(), jdbc.queryForObject(
                "SELECT id FROM mcp_server WHERE mcp_server_code = ?", Long.class, MCP_CODE));

        McpServer second = new McpServer();
        second.setMcpServerCode(MCP_CODE + "-2");
        second.setUserId(9_151_000L);
        second.setName("acceptance-mapping-2");
        second.setDeployConfig("{}");
        assertEquals(1, mcpServerMapper.insert(second));
        assertTrue(second.getId() > server.getId(), "IDENTITY 应单调递增");
    }

    @Test
    void numericKeepsItsDeclaredScale() {
        BigDecimal ctr = new BigDecimal("0.123456");
        jdbc.update("""
                INSERT INTO picture_stats (id, picture_id, ctr) VALUES (?, ?, ?)
                """, STATS_ID, PICTURE_ID, ctr);

        var stored = jdbc.queryForObject(
                "SELECT ctr FROM picture_stats WHERE id = ?", BigDecimal.class, STATS_ID);
        assertNotNull(stored);
        assertEquals(6, stored.scale(), "numeric(10,6) 读回应保留 6 位标度，实际: " + stored.toPlainString());
        assertEquals(0, ctr.compareTo(stored));
    }

    @Test
    void aggregatesComeBackAsTheDocumentedJavaTypes() {
        insertPicture(PICTURE_AGG_A, 100, 1);
        insertPicture(PICTURE_AGG_B, 200, 0);

        Object count = jdbc.queryForObject(
                "SELECT count(*) FROM picture WHERE user_id = ?", Object.class, OWNER_ID);
        assertInstanceOf(Long.class, count, "count(*) 在 PG 是 bigint，对应 Long");

        Object widthSum = jdbc.queryForObject(
                "SELECT sum(pic_width) FROM picture WHERE user_id = ?", Object.class, OWNER_ID);
        assertInstanceOf(Long.class, widthSum, "sum(integer) 在 PG 提升为 bigint，不是 MySQL 的 decimal");
        assertEquals(300L, widthSum);

        Object widthAvg = jdbc.queryForObject(
                "SELECT avg(pic_width) FROM picture WHERE user_id = ?", Object.class, OWNER_ID);
        assertInstanceOf(BigDecimal.class, widthAvg, "avg() 在 PG 返回 numeric，对应 BigDecimal");
        assertEquals(0, new BigDecimal("150").compareTo((BigDecimal) widthAvg));

        jdbc.update("""
                INSERT INTO picture_stats (id, picture_id, view_count) VALUES (?, ?, 5)
                """, STATS_ID, PICTURE_ID);
        Object bigintSum = jdbc.queryForObject(
                "SELECT sum(view_count) FROM picture_stats WHERE id = ?", Object.class, STATS_ID);
        assertInstanceOf(BigDecimal.class, bigintSum, "sum(bigint) 在 PG 返回 numeric：对 Long 做强制转换会 ClassCastException");
    }

    @Test
    void smallintMapsToIntegerOnBothJdbcAndEntityPaths() {
        insertPicture(PICTURE_ID, 10, 0);

        assertEquals(Integer.valueOf(0), jdbc.queryForObject(
                "SELECT is_delete FROM picture WHERE id = ?", Integer.class, PICTURE_ID));

        Picture picture = pictureMapper.selectById(PICTURE_ID);
        assertNotNull(picture);
        assertInstanceOf(Integer.class, picture.getIsDelete(), "小整数列迁移后实体字段仍是 Integer，不是 Boolean");
        assertEquals(0, picture.getIsDelete());
        assertInstanceOf(Date.class, picture.getCreateTime());
    }

    @Test
    void timestampWithoutTimeZoneMapsToLocalDateTime() {
        LocalDateTime withFraction = LocalDateTime.of(2022, 3, 4, 5, 6, 7, 123_000_000);
        jdbc.update("""
                INSERT INTO picture (id, url, name, user_id, create_time, edit_time, update_time)
                VALUES (?, 'https://acceptance.invalid/t.png', 'timestamp', 9_151_000, ?, ?, ?)
                """, PICTURE_ID, withFraction, withFraction, withFraction);

        LocalDateTime stored = jdbc.queryForObject(
                "SELECT create_time FROM picture WHERE id = ?", LocalDateTime.class, PICTURE_ID);
        assertEquals(LocalDateTime.of(2022, 3, 4, 5, 6, 7), stored,
                "timestamp(0) 抹掉小数秒；读回值是本地墙钟，不含时区偏移");
        assertEquals(0, stored.getNano());
        assertEquals(stored, jdbc.queryForObject(
                "SELECT date_trunc('second', create_time) FROM picture WHERE id = ?",
                LocalDateTime.class, PICTURE_ID),
                "整库时间都应落在整秒上，便于 API 输出与前端解析保持一致");
    }

    @Test
    void noColumnWasTurnedIntoBoolean() {
        // Flyway 自己的 schema history 有一个 success boolean 列，不是业务表，必须排除。
        Long booleans = jdbc.queryForObject("""
                SELECT count(*) FROM information_schema.columns
                WHERE table_schema = 'public' AND data_type = 'boolean'
                  AND table_name <> 'flyway_schema_history'
                """, Long.class);
        assertEquals(0L, booleans, "Boolean 语义本轮不重构：0/1 继续用 smallint 表达");
    }

    private void insertPicture(long id, int width, int isDelete) {
        jdbc.update("""
                INSERT INTO picture (id, url, name, user_id, pic_width, is_delete)
                VALUES (?, ?, ?, ?, ?, ?)
                """, id, "https://acceptance.invalid/" + id + ".png", "width-" + width, OWNER_ID, width, isDelete);
    }
}
