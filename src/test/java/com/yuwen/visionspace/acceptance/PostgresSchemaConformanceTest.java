package com.yuwen.visionspace.acceptance;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;

import java.util.List;
import java.util.Map;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * 迁移后基线的形状一致性，跑在真实 PostgreSQL 上。
 *
 * <p>MySQL 迁移演练脚本已退役：现在没有「把旧库升级成新库」这件事，取而代之的是
 * 锁住基线本身的形状——表数量、命名、类型、IDENTITY、索引与触发器函数。任何
 * 后来的改动让这些事实漂移（多一张表、混进 camelCase 列、把 timestamp(0) 改成
 * 带时区、把 IDENTITY 换成手写序列），都必须在这里显式修改期望值，而不是悄悄改变。
 */
@IsolatedSpringBootTest
class PostgresSchemaConformanceTest {

    /** Flyway 基线 v1 建出的业务表；新增表必须同时改这里与基线。 */
    private static final Set<String> BASELINE_TABLES = Set.of(
            "agent_action_record", "agent_legacy_attachment", "agent_message", "agent_run_state",
            "agent_session", "agent_session_attachment", "app_user", "asset_board",
            "asset_board_operation", "asset_board_proposal", "asset_search_snapshot",
            "feedback_attachment", "mcp_server", "picture", "picture_action_event_dedupe",
            "picture_file", "picture_index_task", "picture_stats", "resource_access_grant",
            "resource_isolation", "space", "space_user", "storage_cleanup_task", "storage_config",
            "storage_switch_confirm", "storage_switch_state", "user_feedback", "user_picture_action",
            "user_preference", "vip_redemption_code", "vip_redemption_record");

    /**
     * 保留 MySQL AUTO_INCREMENT 语义的表：6 张是 MyBatis Plus {@code IdType.AUTO} 实体，
     * 另外 7 张有「插入时不带 id」的自定义 SQL（agent/统计/偏好等）。其余表由应用写雪花 id；
     * {@code GENERATED BY DEFAULT} 同时允许显式 id，两种写入路径都能用。
     */
    /** MySQL 侧全部 AUTO_INCREMENT 的 24 张表：PG 侧必须一一对应为 IDENTITY。 */
    private static final Set<String> IDENTITY_TABLES = Set.of(
            "agent_action_record", "agent_legacy_attachment", "agent_message", "agent_run_state",
            "agent_session", "agent_session_attachment", "app_user", "feedback_attachment",
            "mcp_server", "picture", "picture_file", "picture_index_task", "picture_stats",
            "resource_access_grant", "resource_isolation", "space", "space_user",
            "storage_cleanup_task", "storage_config", "user_feedback", "user_picture_action",
            "user_preference", "vip_redemption_code", "vip_redemption_record");

    @Autowired
    private JdbcTemplate jdbc;

    @Test
    void baselineCreatesExactlyTheTrackedTables() {
        List<String> tables = jdbc.queryForList("""
                SELECT table_name FROM information_schema.tables
                WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
                  AND table_name <> 'flyway_schema_history'
                ORDER BY table_name
                """, String.class);
        assertEquals(BASELINE_TABLES.stream().sorted().toList(), tables,
                "基线表集合发生变化：新增/删除表必须同步更新本用例的期望值");
    }

    @Test
    void noColumnKeepsCamelCase() {
        List<String> offenders = jdbc.queryForList("""
                SELECT table_name || '.' || column_name FROM information_schema.columns
                WHERE table_schema = 'public' AND column_name <> lower(column_name)
                """, String.class);
        assertEquals(List.of(), offenders, "库内标识符统一 snake_case，camelCase 列会让未加引号的 SQL 直接找不到列");
    }

    /** MySQL 侧带 {@code isDelete} 的六张表；多一张少一张都会改变逻辑删除的语义边界。 */
    private static final Set<String> LOGICAL_DELETE_TABLES = Set.of(
            "agent_session", "app_user", "picture", "space", "storage_config", "user_feedback");

    @Test
    void logicalDeleteFlagsStaySmallint() {
        List<Map<String, Object>> columns = jdbc.queryForList("""
                SELECT table_name, data_type FROM information_schema.columns
                WHERE table_schema = 'public' AND column_name = 'is_delete'
                ORDER BY table_name
                """);
        assertEquals(LOGICAL_DELETE_TABLES.stream().sorted().toList(),
                columns.stream().map(column -> column.get("table_name")).toList(),
                "逻辑删除只覆盖这六张表：新增/删除 is_delete 列必须显式改这里");
        for (Map<String, Object> column : columns) {
            assertEquals("smallint", column.get("data_type"),
                    column.get("table_name") + ".is_delete 保持 smallint（0/1），实体侧仍是 Integer");
        }
    }

    @Test
    void businessTimestampsAreSecondPrecisionWithoutTimeZone() {
        List<String> offenders = jdbc.queryForList("""
                SELECT table_name || '.' || column_name || ':' || data_type || '(' || coalesce(datetime_precision::text, '?') || ')'
                FROM information_schema.columns
                WHERE table_schema = 'public'
                  AND table_name <> 'flyway_schema_history'
                  AND data_type LIKE 'timestamp%'
                  AND (data_type <> 'timestamp without time zone' OR datetime_precision <> 0)
                """, String.class);
        assertEquals(List.of(), offenders, "业务时间统一 timestamp(0) 无时区；带时区或带小数秒会改变 API 的输出形状");
    }

    @Test
    void onlyTheDocumentedTablesUseIdentity() {
        List<String> identityTables = jdbc.queryForList("""
                SELECT table_name FROM information_schema.columns
                WHERE table_schema = 'public' AND is_identity = 'YES'
                ORDER BY table_name
                """, String.class);
        assertEquals(IDENTITY_TABLES.stream().sorted().toList(), identityTables,
                "自增列必须覆盖「应用插入时不带 id」的每张表：漏一张就会在上线路径上 NOT NULL 失败");
    }

    @Test
    void legacyUserTableIsGoneAndAccountIndexIsCaseInsensitive() {
        Long legacyTables = jdbc.queryForObject("""
                SELECT count(*) FROM information_schema.tables
                WHERE table_schema = 'public' AND table_name = 'user'
                """, Long.class);
        assertEquals(0L, legacyTables, "user 是 PostgreSQL 保留字，表名必须是 app_user");

        List<String> indexDefs = jdbc.queryForList("""
                SELECT indexdef FROM pg_indexes
                WHERE schemaname = 'public' AND tablename = 'app_user'
                """, String.class);
        // PostgreSQL 会把表达式索引渲染成 lower((user_account)::text)，不能按字面量 lower(user_account) 匹配。
        assertTrue(indexDefs.stream().anyMatch(def -> def.contains("lower(") && def.contains("user_account")),
                "账号唯一索引必须建在 lower(user_account) 上（大小写不敏感），实际: " + indexDefs);
    }

    @Test
    void updateTriggersAreBoundToTheDocumentedFunctionSet() {
        List<String> functions = jdbc.queryForList("""
                SELECT DISTINCT p.proname
                FROM pg_trigger t
                JOIN pg_proc p ON p.oid = t.tgfoid
                WHERE NOT t.tgisinternal
                ORDER BY p.proname
                """, String.class);
        assertEquals(List.of("set_updated_create_time", "set_updated_gmt_modified",
                        "set_updated_time", "set_updated_updated_time"),
                functions, "更新时间触发器只允许复用这四个函数，新增函数会绕开「内容未变不刷新」的语义");

        Long triggerCount = jdbc.queryForObject("""
                SELECT count(*) FROM pg_trigger WHERE NOT tgisinternal
                """, Long.class);
        assertEquals(22L, triggerCount, "触发器数量与「原本有 ON UPDATE CURRENT_TIMESTAMP 的列」一一对应");
    }

    @Test
    void extractedColumnSetsUseTheDocumentedTypes() {
        // bytea 承载 Agent 状态快照，numeric 承载点击率：两者的 JDBC 映射在迁移测试里单独验证。
        assertEquals("bytea", jdbc.queryForObject("""
                SELECT data_type FROM information_schema.columns
                WHERE table_schema = 'public' AND table_name = 'agent_run_state' AND column_name = 'state_payload'
                """, String.class));
        assertEquals("numeric", jdbc.queryForObject("""
                SELECT data_type FROM information_schema.columns
                WHERE table_schema = 'public' AND table_name = 'picture_stats' AND column_name = 'ctr'
                """, String.class));
    }
}
